def clear_validation_cache(task_id: str = None) -> int:
    """
    Clear validation cache files.

    Args:
        task_id: If provides, only clear files for this task.
                 If None, clear all validation files.

    Returns:
        Number of files deleted.
    """
    results_dir = _get_results_dir()
    deleted = 0

    if task_id:
        pattern = f"{task_id}*"
    else:
        pattern = "*"

    for ext in [".dck", ".log", ".lst", ".out"]:
        for f in results_dir.glob(f"{pattern}{ext}"):
            try:
                f.unlink()
                deleted += 1
            except Exception:
                pass

    logger.info(f"Cleared {deleted} validation files")
    return deleted


def get_validation_stats() -> Dict[str, Any]:
    """
    Get statistics about validation files.

    Returns:
        Dictionary with validation statistics.
    """
    results_dir = _get_results_dir()

    dck_files = list(results_dir.glob("*.dck"))
    log_files = list(results_dir.glob("*.log"))
    lst_files = list(results_dir.glob("*.lst"))

    # Count errors in log files
    error_count = 0
    for log_file in log_files:
        try:
            content = log_file.read_text(encoding="utf-8", errors="ignore")
            if "error" in content.lower() or "fatal" in content.lower():
                error_count += 1
        except Exception:
            pass

