"""
TRNSYS Validation Tools for TRNSYS DCK Generator.

Provides @tool decorated functions for DCK file validation using TrnEXE64.exe.
These tools are used by the validator agent to verify generated DCK files.

Tool Categories:
1. Validation Execution
   - run_trnsys_validation: Execute TrnEXE64.exe to validate DCK
   - get_validation_status: Check validation status for a task

2. Error Analysis
   - parse_error_log: Parse .log and .lst files for errors
   - analyze_validation_errors: LLM-driven error analysis (NOT hardcoded rules)

Key Design Principles:
- Error analysis uses LLM, NOT hardcoded if-else rules
- All validation results are structured for downstream processing
- Supports iterative repair workflow
"""

