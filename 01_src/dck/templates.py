"""
DCK Template System for TRNSYS DCK Generator.

This module provides template management for generating DCK files.
Templates are learned from the 176 training set DCK files.

Key Features:
1. DCKSection enum for different DCK file sections
2. Template classes for each section type
3. DCKTemplateManager for template retrieval and management
4. Support for the "copy when possible" principle

Design Principles:
- NO hardcoded DCK generation rules
- Templates are derived from training set analysis
- LLM-driven customization of templates
"""

from __future__ import annotations

import json
import logging
import re
from abc import ABC, abstractmethod
from dataclasses import dataclass, field
from datetime import datetime
from enum import Enum
from functools import lru_cache
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple

logger = logging.getLogger(__name__)


class DCKSection(str, Enum):
    """DCK file sections."""

    VERSION = "version"
    HEADER = "header"
    CONSTANTS = "constants"
    SIMULATION = "simulation"
    TOLERANCES = "tolerances"
    LIMITS = "limits"
    SOLVER = "solver"
    EQUATIONS = "equations"
    UNIT = "unit"
    EXTERNAL_FILES = "external_files"
    END = "end"
    LINK_STYLE = "link_style"


@dataclass
class TemplateVariable:
    """A variable in a template that can be substituted."""

    name: str
    default_value: Any = None
    description: str = ""
    required: bool = False


@dataclass
class DCKTemplate:
    """Base class for DCK templates."""

    section: DCKSection
    content: str
    variables: List[TemplateVariable] = field(default_factory=list)
    source_file: str = ""
    description: str = ""

    def render(self, **kwargs) -> str:
        """
        Render the template with given variables.

        Args:
            **kwargs: Variable values to substitute.

        Returns:
            Rendered template string.
        """
        result = self.content

        for var in self.variables:
            placeholder = f"{{{var.name}}}"
            value = kwargs.get(var.name, var.default_value)

            if value is None and var.required:
                raise ValueError(f"Required variable '{var.name}' not provides")

            if value is not None:
                result = result.replace(placeholder, str(value))

        return result


class HeaderTemplate:
    """Template for DCK file header section."""

    TEMPLATE = """VERSION 18
*******************************************************************************
*** TRNSYS input file
*** Generated by LLM-based Multi-Agent System
*** Date: {timestamp}
*** Task: {task_description}
***
*** This file was automatically generated. Manual editing may cause issues.
*******************************************************************************"""

    @classmethod
    def render(cls, task_description: str = "", timestamp: str = None) -> str:
        """Render the header template."""
        if timestamp is None:
            timestamp = datetime.now().strftime("%Y-%m-%d %H:%M:%S")

        # Sanitize task description: remove non-ASCII characters (Chinese, etc.)
        # TRNSYS cannot parse non-ASCII characters in DCK files
        sanitized_desc = ''.join(c if ord(c) < 128 else '' for c in task_description)
        sanitized_desc = ' '.join(sanitized_desc.split())  # Normalize whitespace

        # Truncate task description if too long
        if len(sanitized_desc) > 100:
            sanitized_desc = sanitized_desc[:97] + "..."

        # If sanitized description is empty, use a default
        if not sanitized_desc.strip():
            sanitized_desc = "TRNSYS simulation"

        return cls.TEMPLATE.format(
            timestamp=timestamp,
            task_description=sanitized_desc,
        )


class ControlCardsTemplate:
    """Template for DCK control cards section."""

    # Template matches training DCK format exactly
    TEMPLATE = """*******************************************************************************
*** Control cards
*******************************************************************************
* START, STOP and STEP
CONSTANTS 3
START={start_time}
STOP={stop_time}
STEP={time_step}
SIMULATION 	 START	 STOP	 STEP	! Start time	End time	Time step
TOLERANCES {integration_tol} {convergence_tol}			! Integration	 Convergence
LIMITS {max_iterations} {max_warnings} {trace_limit}				! Max iterations	Max warnings	Trace limit
DFQ {dfq}					! TRNSYS numerical integration solver method
WIDTH {width}				! TRNSYS output file width, number of characters
LIST 					! NOLIST statement
					! MAP statement
SOLVER {solver_type} {min_relaxation} {max_relaxation}				! Solver statement	Minimum relaxation factor	Maximum relaxation factor
NAN_CHECK {nan_check}				! Nan DEBUG statement
OVERWRITE_CHECK {overwrite_check}			! Overwrite DEBUG statement
TIME_REPORT {time_report}			! disable time report
EQSOLVER {eqsolver}				! EQUATION SOLVER statement
* User defined CONSTANTS
*$USER_CONSTANTS
{user_constants_block}*$USER_CONSTANTS_END"""

    @classmethod
    def render(
        cls,
        start_time: float = 0,
        stop_time: float = 8760,
        time_step: float = 1,
        additional_constants: List[Dict[str, Any]] = None,
        integration_tol: float = 0.001,
        convergence_tol: float = 0.001,
        max_iterations: int = 30,
        max_warnings: int = 30,
        trace_limit: int = 30,
        dfq: int = 1,
        width: int = 80,
        solver_type: int = 0,
        min_relaxation: float = 1,
        max_relaxation: float = 1,
        nan_check: int = 0,
        overwrite_check: int = 0,
        time_report: int = 0,
        eqsolver: int = 0,
    ) -> str:
        """Render the control cards template."""
        # Build user-defined constants block
        user_constants_block = ""
        if additional_constants:
            const_lines = []
            for const in additional_constants:
                name = const.get("name", "")
                # USER_CONSTANTS are TRNSYS expressions (may reference built-in
                # time variables START/STOP), declared via the EQUATIONS keyword.
                # Prefer the "expression" field; fall back to legacy "value" for
                # backward compatibility with any previously stored constants.
                expr = const.get("expression")
                if expr is None or expr == "":
                    expr = const.get("value", 0)
                if name:
                    const_lines.append(f"{name}={expr}")

            if const_lines:
                user_constants_block = f"EQUATIONS {len(const_lines)}\n" + "\n".join(const_lines) + "\n"

        return cls.TEMPLATE.format(
            start_time=start_time,
            stop_time=stop_time,
            time_step=time_step,
            user_constants_block=user_constants_block,
            integration_tol=integration_tol,
            convergence_tol=convergence_tol,
            max_iterations=max_iterations,
            max_warnings=max_warnings,
            trace_limit=trace_limit,
            dfq=dfq,
            width=width,
            solver_type=solver_type,
            min_relaxation=min_relaxation,
            max_relaxation=max_relaxation,
            nan_check=nan_check,
            overwrite_check=overwrite_check,
            time_report=time_report,
            eqsolver=eqsolver,
        )


class UnitTemplate:
    """Template for UNIT blocks."""

    TEMPLATE = """* Model "{unit_name}" (Type {type_number})
*

UNIT {unit_number} TYPE {type_number}	 {unit_name}
*$UNIT_NAME {unit_name}
*$MODEL {model_path}
*$POSITION {position_x} {position_y}
*$LAYER {layer} #
{parameters_block}
{inputs_block}
{specific_properties_block}
{labels_block}
{external_files_block}
*------------------------------------------------------------------------------"""

    PARAMETERS_TEMPLATE = """PARAMETERS {num_params}
{param_lines}"""

    INPUTS_TEMPLATE = """INPUTS {num_inputs}
{input_lines}
*** INITIAL INPUT VALUES
{initial_values}"""

    LABELS_TEMPLATE = """LABELS  {num_labels}
{label_lines}"""

    @classmethod
    def render(
        cls,
        unit_number: int,
        type_number: str,
        unit_name: str,
        parameters: List[Dict[str, Any]] = None,
        inputs: List[Dict[str, Any]] = None,
        initial_values: List[Any] = None,
        position_x: int = 100,
        position_y: int = 100,
        layer: str = "Main",
        model_path: str = "",
        external_files: List[Dict[str, str]] = None,
        labels: List[str] = None,
        specific_properties: List[Dict[str, Any]] = None,
    ) -> str:
        """Render a UNIT block."""
        # Normalize layer value to "Main" to ensure consistency
        # LLM may output "Source", "Processing", "Equipment", "Output" etc.
        # but TRNSYS Studio standard format uses "Main" for all components
        VALID_LAYERS = ["Main"]
        if layer not in VALID_LAYERS:
            logger.debug(f"Normalizing layer '{layer}' to 'Main' for unit {unit_number}")
            layer = "Main"

        # Extract type ID (remove 'Type' prefix if present)
        type_id = re.sub(r'^Type', '', str(type_number), flags=re.IGNORECASE)

        # Extract BASE type number for UNIT declaration (e.g., "15-6" -> "15", "65d" -> "65")
        # TRNSYS UNIT declaration only accepts numeric type numbers
        base_type_match = re.match(r'^(\d+)', type_id)
        base_type_num = base_type_match.group(1) if base_type_match else type_id

        # Build parameters block
        parameters_block = ""
        if parameters:
            param_lines = []
            for i, param in enumerate(parameters, 1):
                if isinstance(param, dict):
                    value = param.get("value", 0)
                    desc = param.get("name", f"Parameter {i}")
                    param_lines.append(f"{value}\t\t! {i} {desc}")
                else:
                    param_lines.append(f"{param}\t\t! {i}")

            parameters_block = cls.PARAMETERS_TEMPLATE.format(
                num_params=len(parameters),
                param_lines="\n".join(param_lines),
            )

        # Build inputs block
        inputs_block = ""
        if inputs:
            input_lines = []
            for inp in inputs:
                if isinstance(inp, dict):
                    # Check if source is an equation (variable name) or component (unit,output)
                    source_type = inp.get("source_type", "component")
                    variable_name = inp.get("variable_name", "") or inp.get("source_variable", "")

                    if source_type == "equation" and variable_name:
                        # Input from equation: use variable name directly
                        desc = inp.get("name", "")
                        if desc:
                            input_lines.append(f"{variable_name}\t\t! {desc}")
                        else:
                            input_lines.append(variable_name)
                    else:
                        # Input from component: use unit,output format
                        src_unit = inp.get("source_unit", 0)
                        src_out = inp.get("source_output", 0)
                        desc = inp.get("name", "")
                        if desc:
                            input_lines.append(f"{src_unit},{src_out}\t\t! {desc}")
                        else:
                            input_lines.append(f"{src_unit},{src_out}")
                else:
                    input_lines.append(str(inp))

            # Build initial values
            if initial_values:
                init_str = " ".join(str(v) for v in initial_values)
            else:
                init_str = " ".join(["0"] * len(inputs))

            inputs_block = cls.INPUTS_TEMPLATE.format(
                num_inputs=len(inputs),
                input_lines="\n".join(input_lines),
                initial_values=init_str,
            )

        # Build specific_properties block
        # This handles the specific_properties from connection_generator
        # specific_properties format: [{"specific_property": "desc", "note": "LABELS/ASSIGN/FORMAT", "default": "value"}, ...]
        # IMPORTANT: Preserve original order of properties as defined in TMF specification.
        # Properties before LABELS (e.g., units line in Type65b) must appear before the LABELS line in DCK.
        specific_properties_block = ""
        if specific_properties is not None:
            output_lines = []

            for prop in specific_properties:
                if isinstance(prop, dict):
                    note = prop.get("note", "").upper()
                    value = prop.get("value", prop.get("default", ""))

                    if note == "FORMAT":
                        # FORMAT properties are internal use, not written to DCK
                        continue
                    elif note == "ASSIGN":
                        # ASSIGN properties go to external_files_block (handled below)
                        continue
                    elif "LABELS" in note:
                        # LABELS line: extract count from note or use value
                        count_part = note.replace("LABELS", "").strip()
                        if count_part:
                            output_lines.append(f"LABELS {count_part}")
                        else:
                            output_lines.append(f"LABELS  {value}")
                    else:
                        # No note or unknown note: direct value output
                        output_lines.append(str(value))

            if output_lines:
                specific_properties_block = "\n".join(output_lines)

            # ASSIGN properties go to external_files_block (handled below)

        # Build labels block (for Type65 and similar components)
        # NOTE: This is the OLD labels field, kept for backward compatibility
        # New code should use specific_properties instead
        labels_block = ""
        if labels:
            label_lines = []
            for label in labels:
                # Ensure label is quoted
                if not label.startswith('"'):
                    label = f'"{label}"'
                label_lines.append(label)
            labels_block = cls.LABELS_TEMPLATE.format(
                num_labels=len(labels),
                label_lines="\n".join(label_lines),
            )

        # Build external files block
        # This includes both external_files and ASSIGN-type specific_properties
        external_files_block = ""
        file_lines = []

        # Add ASSIGN properties from specific_properties
        if specific_properties is not None:
            assign_props = []
            for prop in specific_properties:
                if isinstance(prop, dict):
                    note = prop.get("note", "").upper()
                    if note == "ASSIGN":
                        value = prop.get("value", prop.get("default", ""))
                        assign_props.append(value)

            if assign_props:
                if not file_lines:
                    file_lines.append("*** External files")
                for assign_value in assign_props:
                    # ASSIGN format: "path logical_unit" or just "path"
                    # Parse the value to extract path and logical unit
                    parts = assign_value.split()
                    if len(parts) >= 2:
                        path = " ".join(parts[:-1])  # Everything except last part
                        logical_unit = parts[-1]
                        file_lines.append(f'ASSIGN {path} {logical_unit}')
                    else:
                        file_lines.append(f'ASSIGN {assign_value}')

        # Add traditional external_files
        if external_files:
            if not file_lines:
                file_lines.append("*** External files")
            for ef in external_files:
                path = ef.get("path", ef.get("file_path", ""))
                logical_unit = ef.get("logical_unit", 30)
                prompt = ef.get("prompt", "") or ef.get("description", "")
                file_lines.append(f'ASSIGN "{path}" {logical_unit}')
                if prompt:
                    file_lines.append(f"*|? {prompt} |1000")

        if file_lines:
            external_files_block = "\n".join(file_lines)

        # Default model path if not provides
        if not model_path:
            model_path = f".\\Type{type_id}.tmf"

        result = cls.TEMPLATE.format(
            unit_number=unit_number,
            type_number=base_type_num,  # Use base type number for UNIT declaration
            unit_name=unit_name,
            model_path=model_path,
            position_x=position_x,
            position_y=position_y,
            layer=layer,
            parameters_block=parameters_block,
            inputs_block=inputs_block,
            specific_properties_block=specific_properties_block,
            labels_block=labels_block,
            external_files_block=external_files_block,
        )

        # Clean up multiple consecutive blank lines
        while "\n\n\n" in result:
            result = result.replace("\n\n\n", "\n\n")

        # Remove blank lines before *** External files
        result = re.sub(r'\n\n+(\*\*\* External files)', r'\n\1', result)

        # Remove blank lines immediately before the separator line
        result = re.sub(r'\n\n+(\*-{10,})', r'\n\1', result)

        return result


class EquationsTemplate:
    """Template for EQUATIONS blocks.

    IMPORTANT: EQUATIONS blocks are INDEPENDENT - they do NOT belong to any UNIT block!
    """

    # CORRECT format: Independent EQUATIONS block (NOT wrapped in UNIT)
    TEMPLATE = """* EQUATIONS "{unit_name}"
*
EQUATIONS {num_equations}
{equation_lines}
*$UNIT_NAME {unit_name}
*$LAYER {layer}
*$POSITION {position_x} {position_y}
*$UNIT_NUMBER {unit_number}
*------------------------------------------------------------------------------"""

    @classmethod
    def render(
        cls,
        unit_number: int,
        unit_name: str,
        equations: List,
        position_x: int = 100,
        position_y: int = 100,
        layer: str = "Main",
    ) -> str:
        """Render an EQUATIONS block (independent, NOT wrapped in UNIT).

        Args:
            equations: List of equation strings or dicts with keys:
                       {"variable": str, "expression": str, "comment": str}
        """
        # Normalize layer value to "Main" to ensure consistency
        VALID_LAYERS = ["Main"]
        if layer not in VALID_LAYERS:
            logger.debug(f"Normalizing layer '{layer}' to 'Main' for equations block {unit_number}")
            layer = "Main"

        # Convert dict equations to formatted strings with comments
        eq_lines = []
        for eq in equations:
            if isinstance(eq, dict):
                var = eq.get("variable", "")
                expr = eq.get("expression", "")
                comment = eq.get("comment", "")
                line = f"{var} = {expr}"
                if comment:
                    line += f" ! {comment}"
                eq_lines.append(line)
            else:
                # Already a string
                eq_lines.append(str(eq))

        equation_lines = "\n".join(eq_lines)

        return cls.TEMPLATE.format(
            unit_number=unit_number,
            unit_name=unit_name,
            position_x=position_x,
            position_y=position_y,
            layer=layer,
            num_equations=len(equations),
            equation_lines=equation_lines,
        )


class LinkStyleTemplate:
    """Template for LINK_STYLE blocks."""

    @classmethod
    def render(cls, links: List[Dict[str, Any]]) -> str:
        """Render LINK_STYLE block."""
        if not links:
            return ""

        lines = ["*!LINK_STYLE"]

        for link in links:
            from_unit = link.get("from_unit")
            to_unit = link.get("to_unit")
            if from_unit is not None and to_unit is not None:
                lines.append(f"*!LINK {from_unit}:{to_unit}")

                # Add connection set if available
                connection_set = link.get("connection_set", "")
                if connection_set:
                    lines.append(f"*!CONNECTION_SET {connection_set}")

        lines.append("*!LINK_STYLE_END")

        return "\n".join(lines)


class DCKTemplateManager:
    """
    Manager for DCK templates.

    Provides template retrieval and management based on training set analysis.
    Supports the "copy when possible" principle.
    """

    def __init__(self, training_data_path: Path = None):
        """
        Initialize the template manager.

        Args:
            training_data_path: Path to training set DCK data.
        """
        self._training_data_path = training_data_path
        self._unit_templates: Dict[str, List[str]] = {}
        self._loaded = False

    def _ensure_loaded(self):
        """Ensure training data is loaded."""
        if not self._loaded:
            self._load_templates_from_training_set()
            self._loaded = True

    def _load_templates_from_training_set(self):
        """
        Load and analyze templates from training set DCK files.

        This method extracts common patterns from the 176 training DCK files.
        """
        if self._training_data_path is None:
            # Try to get path from config
            try:
                from ..core.config import get_settings
                settings = get_settings()
                self._training_data_path = settings.train_dck_dir
            except Exception as e:
                logger.warning(f"Could not load training data path: {e}")
                return

        if not self._training_data_path or not self._training_data_path.exists():
            logger.warning(f"Training data path not found: {self._training_data_path}")
            return

        # Load DCK files and extract UNIT patterns by type
        try:
            for dck_file in self._training_data_path.glob("*.dck"):
                self._extract_unit_patterns(dck_file)

            logger.info(f"Loaded templates for {len(self._unit_templates)} component types")
        except Exception as e:
            logger.error(f"Error loading templates: {e}")

    def _extract_unit_patterns(self, dck_file: Path):
        """Extract UNIT block patterns from a DCK file."""
        try:
            content = dck_file.read_text(encoding='utf-8', errors='ignore')

            # Find all UNIT blocks
            unit_pattern = r'UNIT\s+(\d+)\s+TYPE\s+(\d+)\s+(\S+)(.*?)(?=UNIT\s+\d+\s+TYPE|\*-{10,}|END\s*$)'
            matches = re.findall(unit_pattern, content, re.DOTALL | re.IGNORECASE)

            for match in matches:
                unit_num, type_num, unit_name, block_content = match
                type_key = f"Type{type_num}"

                if type_key not in self._unit_templates:
                    self._unit_templates[type_key] = []

                # Store the full UNIT block
                full_block = f"UNIT {unit_num} TYPE {type_num} {unit_name}{block_content}"
                self._unit_templates[type_key].append(full_block.strip())

        except Exception as e:
            logger.debug(f"Error extracting patterns from {dck_file}: {e}")

    def get_header_template(self) -> HeaderTemplate:
        """Get the header template."""
        return HeaderTemplate

    def get_control_cards_template(self) -> ControlCardsTemplate:
        """Get the control cards template."""
        return ControlCardsTemplate

    def get_unit_template(self) -> UnitTemplate:
        """Get the unit template."""
        return UnitTemplate

    def get_equations_template(self) -> EquationsTemplate:
        """Get the equations template."""
        return EquationsTemplate

    def get_link_style_template(self) -> LinkStyleTemplate:
        """Get the link style template."""
        return LinkStyleTemplate

    def get_unit_examples(self, type_id: str, limit: int = 3) -> List[str]:
        """
        Get example UNIT blocks for a specific type from training set.

        This supports the "copy when possible" principle by providing real examples.

        Args:
            type_id: The Type ID (e.g., "Type15", "Type56", "15", "56").
            limit: Maximum number of examples to return.

        Returns:
            List of example UNIT block strings.
        """
        self._ensure_loaded()

        # Normalize type_id
        if not type_id.lower().startswith("type"):
            type_id = f"Type{type_id}"

        examples = self._unit_templates.get(type_id, [])
        return examples[:limit]

    def get_similar_unit_examples(
        self,
        type_ids: List[str],
        limit: int = 5,
    ) -> Dict[str, List[str]]:
        """
        Get example UNIT blocks for multiple types.

        Args:
            type_ids: List of Type IDs.
            limit: Maximum examples per type.

        Returns:
            Dictionary mapping type_id to list of examples.
        """
        self._ensure_loaded()

        result = {}
        for type_id in type_ids:
            examples = self.get_unit_examples(type_id, limit)
            if examples:
                result[type_id] = examples

        return result

    def render_header(self, task_description: str = "") -> str:
        """Render the header section."""
        return HeaderTemplate.render(task_description=task_description)

    def render_control_cards(
        self,
        simulation_settings: Dict[str, Any] = None,
        constants: List[Dict[str, Any]] = None,
    ) -> str:
        """Render the control cards section."""
        settings = simulation_settings or {}

        # LIMITS statement defaults come from performance_config (single source of truth)
        from ..core.performance_config import get_performance_config
        perf_config = get_performance_config()

        return ControlCardsTemplate.render(
            start_time=settings.get("start_time", 0),
            stop_time=settings.get("stop_time", 8760),
            time_step=settings.get("time_step", 1),
            additional_constants=constants,
            integration_tol=settings.get("integration_tolerance", 0.001),
            convergence_tol=settings.get("convergence_tolerance", 0.001),
            max_iterations=settings.get("max_iterations", perf_config.limits_iterations_before_warning),
            max_warnings=settings.get("max_warnings", perf_config.limits_warnings_before_error),
            trace_limit=settings.get("trace_limit", perf_config.limits_iterations_before_trace),
        )

    def render_unit(self, component: Dict[str, Any]) -> str:
        """Render a UNIT block for a component."""
        return UnitTemplate.render(
            unit_number=component.get("unit_number", 1),
            type_number=component.get("type_number", "1"),
            unit_name=component.get("unit_name", "Unit"),
            parameters=component.get("parameters", []),
            inputs=component.get("inputs", []),
            initial_values=component.get("initial_values", []),
            position_x=component.get("position_x", 100),
            position_y=component.get("position_y", 100),
            layer=component.get("layer", "Main"),
            model_path=component.get("model_path", ""),
            external_files=component.get("external_files", []),
        )

    def render_equations(self, equation_block: Dict[str, Any]) -> str:
        """Render an EQUATIONS block."""
        return EquationsTemplate.render(
            unit_number=equation_block.get("unit_number", 10),
            unit_name=equation_block.get("unit_name", "Equations"),
            equations=equation_block.get("equations", []),
            position_x=equation_block.get("position_x", 100),
            position_y=equation_block.get("position_y", 100),
            layer=equation_block.get("layer", "Main"),
        )

    def render_link_styles(self, layout_styles: List[Dict[str, Any]]) -> str:
        """Render the LINK_STYLE section."""
        return LinkStyleTemplate.render(layout_styles)


# Global template manager instance
_template_manager: Optional[DCKTemplateManager] = None


def get_template_manager() -> DCKTemplateManager:
    """Get the global template manager instance."""
    global _template_manager
    if _template_manager is None:
        _template_manager = DCKTemplateManager()
    return _template_manager


