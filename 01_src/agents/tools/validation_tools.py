VALIDATION_TIMEOUT = 120

# Results directory for temporary files
_results_dir: Optional[Path] = None


def _get_results_dir() -> Path:
    """Get the results directory for validation files."""
    global _results_dir

    if _results_dir is not None and _results_dir.exists():
        return _results_dir

    try:
        from ...core.config import get_settings
        settings = get_settings()
        _results_dir = settings.data_dir / "results" / "validation"
        _results_dir.mkdir(parents=True, exist_ok=True)
    except Exception:
        _results_dir = Path(tempfile.gettempdir()) / "trnsys_validation"
        _results_dir.mkdir(parents=True, exist_ok=True)

    return _results_dir


def _get_trnsys_exe() -> str:
    """Get the TRNSYS executable path."""
    try:
        from ...core.config import get_settings
        settings = get_settings()
        exe_path = settings.trnsys_exe_path
        if exe_path and Path(exe_path).exists():
            return str(exe_path)
    except Exception:
        pass

    # Fallback to environment variable or default
    return os.environ.get("TRNSYS_EXE", DEFAULT_TRNSYS_EXE)


def _run_trnsys_exe(dck_path: Path, timeout: int = VALIDATION_TIMEOUT) -> Dict[str, Any]:
    """
    Run TrnEXE64.exe on a DCK file.

    Args:
        dck_path: Path to the DCK file
        timeout: Timeout in seconds

    Returns:
        Dictionary with execution results
    """
    trnsys_exe = _get_trnsys_exe()

    if not trnsys_exe_exists(trnsys_exe):
        return {
            "success": False,
            "error": f"TrnEXE64.exe not found at: {trnsys_exe}",
            "return_code": -1,
        }

    if not dck_path.exists():
        return {
            "success": False,
            "error": f"DCK file not found: {dck_path}",
            "return_code": -1,
        }

    # Build command with hidden batch mode (/h)
    cmd = build_trnsys_cmd(trnsys_exe, str(dck_path), "/h")

    # Windows-specific settings
    creationflags = 0
    if os.name == "nt":
        try:
            creationflags = subprocess.CREATE_NO_WINDOW
        except AttributeError:
            pass

    # Run in DCK directory
    workdir = dck_path.parent

    try:
        result = subprocess.run(
            cmd,
            capture_output=True,
            text=True,
            timeout=timeout,
            cwd=str(workdir),
            creationflags=creationflags,
        )

        return {
            "success": result.returncode == 0,
            "return_code": result.returncode,
            "stdout": result.stdout,
            "stderr": result.stderr,
        }

    except subprocess.TimeoutExpired:
        return {
            "success": False,
            "error": f"Validation timed out after {timeout} seconds",
            "return_code": -2,
        }
    except Exception as e:
        return {
            "success": False,
            "error": str(e),
            "return_code": -3,
        }


def _read_log_file(dck_path: Path) -> str:
    """Read the .log file generated by TRNSYS."""
    log_path = dck_path.with_suffix(".log")
    if log_path.exists():
        try:
            return log_path.read_text(encoding="utf-8", errors="ignore")
        except Exception as e:
            return f"Error reading log file: {e}"
    return ""


def _read_lst_file(dck_path: Path) -> str:
    """Read the .lst file generated by TRNSYS."""
    lst_path = dck_path.with_suffix(".lst")
    if lst_path.exists():
        try:
            return lst_path.read_text(encoding="utf-8", errors="ignore")
        except Exception as e:
            return f"Error reading lst file: {e}"
    return ""


def _extract_errors_from_log(log_content: str) -> List[Dict[str, Any]]:
    """Extract structured errors from log content."""
    errors = []

    # Pattern for TRNSYS Message errors
    msg_pattern = r'TRNSYS Message\s+(\d+)\s*:\s*([^\n]+)'
    for match in re.finditer(msg_pattern, log_content, re.IGNORECASE):
        errors.append({
            "type": "trnsys_message",
            "code": match.group(1),
            "message": match.group(2).strip(),
            "severity": "error",
        })

    # Pattern for Fatal Error
    fatal_pattern = r'Fatal Error[^\n]*\n([^\n]+)'
    for match in re.finditer(fatal_pattern, log_content, re.IGNORECASE):
        errors.append({
            "type": "fatal_error",
            "message": match.group(1).strip(),
            "severity": "fatal",
        })

    # Pattern for UNIT/TYPE errors
    unit_pattern = r'UNIT\s+(\d+)\s+TYPE\s+(\d+)[^\n]*(?:error|invalid|missing)'
    for match in re.finditer(unit_pattern, log_content, re.IGNORECASE):
        errors.append({
            "type": "unit_error",
            "unit_number": int(match.group(1)),
            "type_number": match.group(2),
            "severity": "error",
        })

    # Pattern for parameter errors
    param_pattern = r'(?:parameter|PARAMETERS)[^\n]*(?:error|invalid|wrong|mismatch)'
    for match in re.finditer(param_pattern, log_content, re.IGNORECASE):
        errors.append({
            "type": "parameter_error",
            "message": match.group(0).strip(),
            "severity": "error",
        })

    # Pattern for input/connection errors
    input_pattern = r'(?:input|INPUTS|connection)[^\n]*(?:error|invalid|missing)'
    for match in re.finditer(input_pattern, log_content, re.IGNORECASE):
        errors.append({
            "type": "connection_error",
            "message": match.group(0).strip(),
            "severity": "error",
        })

    return errors


def _extract_errors_from_lst(lst_content: str) -> List[Dict[str, Any]]:
    """Extract structured errors from lst content."""
    errors = []

    # Pattern for *** errors
    star_pattern = r'\*\*\*[^\n]*(?:error|fatal|invalid)[^\n]*'
    for match in re.finditer(star_pattern, lst_content, re.IGNORECASE):
        errors.append({
            "type": "lst_error",
            "message": match.group(0).strip(),
            "severity": "error",
        })

    # Pattern for line number errors
    line_pattern = r'(?:line|LINE)\s+(\d+)[^\n]*(?:error|invalid)'
    for match in re.finditer(line_pattern, lst_content, re.IGNORECASE):
        errors.append({
            "type": "syntax_error",
            "line_number": int(match.group(1)),
            "message": match.group(0).strip(),
            "severity": "error",
        })

    return errors


